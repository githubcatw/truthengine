/** PDF pages: a string is a text page; null is a scanned page (image only, no text). */
export function pdf(pages: Array<string | null>, opts: { password?: string } = {}): Promise<Buffer> {
  return new Promise((resolve) => {
    const doc = new PDFDocument({ autoFirstPage: false, ...(opts.password ? { userPassword: opts.password, ownerPassword: `${opts.password}-owner` } : {}) });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    for (const p of pages) {
      doc.addPage();
      if (p) doc.fontSize(12).text(p);
      else doc.image(PNG, 50, 50, { width: 200 });
    }
    doc.end();
  });
}
